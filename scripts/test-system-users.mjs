import assert from 'node:assert/strict';
import { build } from 'esbuild';
const compiled = await build({ entryPoints: ['src/api/adapters/mockSystemUsers.ts'], bundle: true, write: false, format: 'esm' });
const { createMockSystemUsers } = await import(`data:text/javascript;base64,${Buffer.from(compiled.outputFiles[0].text).toString('base64')}`);
const business = { id: 1, name: '业务管理员', role: 'super_admin', status: 'active', email: 'business@example.com' };
const config = { sysUserEnabled: true, sysuser: { username: 'system', password: 'system123' } };
const system = createMockSystemUsers(config, business);
assert.throws(() => system.login({ username: 'business', password: 'business123' }));
assert.equal(system.login(config.sysuser).name, '系统管理员');
await system.updateProfile({ name: '独立系统管理员', role: 'forged', status: 'banned' });
assert.equal(system.current().name, '独立系统管理员');
assert.equal(system.current().role, 'super_admin');
assert.equal(business.name, '业务管理员');
await assert.rejects(system.methods.deleteSystemUser(1), /最后一个/);
await assert.rejects(system.methods.updateSystemUser(1, { status: 'inactive' }), /最后一个/);
const added = await system.methods.createSystemUser({ username: 'editor', name: '编辑', password: 'editor123', role: 'content_editor' });
assert(!('password' in added));
assert.equal(system.login({ username: 'editor', password: 'editor123' }).id, added.id);
await system.changePassword('editor123', 'changed123');
assert.throws(() => system.login({ username: 'editor', password: 'editor123' }));
assert.equal(system.login({ username: 'editor', password: 'changed123' }).id, added.id);
await system.methods.updateSystemUser(added.id, { status: 'inactive' });
assert.throws(() => system.login({ username: 'editor', password: 'changed123' }));
await system.methods.deleteSystemUser(added.id);
assert.equal((await system.methods.listSystemUsers()).total, 1);
const disabled = createMockSystemUsers({ sysUserEnabled: false }, business);
await assert.rejects(disabled.methods.listSystemUsers(), /未启用/);
console.log('Separate Mock accounts, profile isolation, passwords, CRUD, disabled mode and last-admin protection passed.');
